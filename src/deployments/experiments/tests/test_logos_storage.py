def config(**kwargs):
    return ExpConfig(image={"repo": "test/storage", "tag": "test"}, **kwargs)


def test_private_network_bootstrap_contract():
    bootstrap = build_nodes("storage-test", config(), bootstrap=True)
    nodes = build_nodes("storage-test", config())
    anchor = bootstrap.spec.template.spec.containers[0]
    node = nodes.spec.template.spec.containers[0]

    assert bootstrap.spec.replicas == 1
    assert nodes.spec.replicas == 2
    assert "--no-bootstrap-node" in anchor.args
    assert "--no-bootstrap-node" not in node.args
    assert "BOOTSTRAP_NODE_URL" not in {env.name for env in anchor.env}
    env = {env.name: env.value for env in node.env}
    assert env["BOOTSTRAP_NODE_URL"] == f"http://{BOOTSTRAP}-service.storage-test.svc:{API_PORT}"
    assert env["BOOTSTRAP_NODE_URL_WAIT"] == "300"
    assert node.command is None  # Must retain the SPR-fetching Docker entrypoint.
    assert node.args[0] == "storage"

    for container in (anchor, node):
        assert container.env[0].name == "POD_IP"
        assert container.env[0].value_from.field_ref.field_path == "status.podIP"
        assert container.env[1].value == "extip:$(POD_IP)"
        assert "--listen-port=2345" in container.args
        assert not any(arg.startswith("--mix-") for arg in container.args)


def test_mix_clients_collect_a_pool_before_starting_and_relays_can_start_without_one():
    cfg = config(mix_enabled=True, num_nodes=7, num_mix_nodes=5)
    bootstrap = build_nodes("storage-test", cfg, bootstrap=True)
    relays = build_nodes("storage-test", cfg, mix_relay=True)
    nodes = build_nodes("storage-test", cfg)
    relay = relays.spec.template.spec.containers[0]
    node = nodes.spec.template.spec.containers[0]

    assert relays.spec.replicas == 5
    assert nodes.spec.replicas == 7
    assert relays.spec.service_name == f"{MIX_RELAYS}-service"
    assert build_service("storage-test", mix_relay=True).spec.selector == (
        relays.spec.selector.match_labels
    )
    assert relay.image == node.image == str(cfg.image)
    assert relay.command is None  # Relay identities are generated by Storage itself.
    assert "--mix-enabled" in relay.args
    assert not any(arg.startswith("--mix-pool") for arg in relay.args)
    assert relays.spec.template.spec.init_containers is None
    assert "--mix-enabled" not in bootstrap.spec.template.spec.containers[0].args

    init = nodes.spec.template.spec.init_containers[0]
    env = {item.name: item.value for item in init.env}
    assert init.image == str(cfg.image)
    assert init.command == ["/bin/bash", "/mix-scripts/prepare_mix.sh"]
    assert env["MIX_RELAYS"].split() == [
        f"storage-mix-{index}.storage-mix-service.storage-test.svc" for index in range(5)
    ]
    assert env["MIX_RELAY_COUNT"] == "5"
    assert env["MIX_SETUP_TIMEOUT"] == "300"
    volumes = {volume.name: volume for volume in nodes.spec.template.spec.volumes}
    assert volumes["mix-scripts"].config_map.name == MIX_SCRIPTS_CONFIG_MAP
    assert volumes["mix-config"].empty_dir is not None
    mounts = {mount.name: mount for mount in node.volume_mounts}
    assert mounts["mix-config"].read_only is True
    assert node.command == ["/bin/bash", "/mix-scripts/start_storage.sh"]
    # The wrapper must still invoke the upstream entrypoint to fetch the bootstrap SPR.
    assert node.args[:2] == ["/docker-entrypoint.sh", "storage"]
    assert "--mix-enabled" in node.args
    assert "--mix-pool=/mix-config/pool.json" in node.args
    assert "BOOTSTRAP_NODE_URL" in {item.name for item in node.env}


@pytest.mark.parametrize("bootstrap", [True, False])
def test_service_routes_to_its_own_group_and_probe_port(bootstrap):
    nodes = build_nodes("storage-test", config(), bootstrap=bootstrap)
    service = build_service("storage-test", bootstrap=bootstrap)
    container = nodes.spec.template.spec.containers[0]

    assert service.spec.selector == nodes.spec.selector.match_labels
    assert nodes.spec.template.metadata.labels == service.spec.selector
    assert service.metadata.name == nodes.spec.service_name
    assert (
        service.spec.selector
        != build_service("storage-test", bootstrap=not bootstrap).spec.selector
    )
    assert service.spec.cluster_ip == "None"
    ports = {port.name: port.container_port for port in container.ports}
    for port in service.spec.ports:
        assert ports[port.target_port] == port.port
        assert port.protocol == "TCP"
    probe = container.readiness_probe.http_get
    assert probe.path == "/api/storage/v1/spr"
    assert ports[probe.port] == API_PORT
    assert nodes.spec.template.spec.volumes[0].empty_dir is not None


