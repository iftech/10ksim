@pytest.mark.asyncio
@pytest.mark.parametrize("mix_enabled", [True, False])
async def test_dry_run_saves_all_manifests_and_runner_metadata(monkeypatch, tmp_path, mix_enabled):
    apply = Mock()
    cleanup = Mock()
    monkeypatch.setattr(base_experiment, "kubectl_apply", apply)
    monkeypatch.setattr(base_experiment, "get_cleanup", cleanup)
    monkeypatch.setattr(LogosStorageExperiment, "_wait_until_clear", Mock())
    transfer = AsyncMock()
    monkeypatch.setattr(logos_storage, "run_file_transfer", transfer)
    exp = LogosStorageExperiment(
        api_client=ApiClient(),
        config=config(verify_transfer=True, num_nodes=4, mix_enabled=mix_enabled),
        namespace="storage-test",
        output_folder=tmp_path,
        dry_run=True,
    )

    await exp.run()

    manifests = [get_YAML().load(path) for path in (tmp_path / "deployment_yamls").glob("*.yaml")]
    # Service and StatefulSet names must not overwrite each other's YAML.
    manifest_count = 12 if mix_enabled else 9
    assert len(manifests) == manifest_count
    assert {manifest["kind"] for manifest in manifests} == {
        "Service",
        "StatefulSet",
        "Pod",
        "ConfigMap",
        "Role",
        "RoleBinding",
    }
    requester = next(manifest for manifest in manifests if manifest["kind"] == "Pod")
    assert requester["spec"]["containers"][0]["image"] == (
        "albertodst/pod-api-requester:logos-storage-v3"
    )
    nodes = next(
        manifest
        for manifest in manifests
        if manifest["kind"] == "StatefulSet" and manifest["metadata"]["name"] == NODES
    )
    containers = nodes["spec"]["template"]["spec"]["containers"]
    assert [container["name"] for container in containers] == ["storage", "storage-verifier"]
    assert containers[1]["image"] == requester["spec"]["containers"][0]["image"]
    assert containers[1]["command"] == ["python", "-m", "routers.storage_verifier"]
    assert containers[1]["args"] == ["--port", "8646", "--storage-port", "8080"]
    assert containers[1]["readinessProbe"]["httpGet"] == {"path": "/healthz", "port": "verifier"}
    for manifest in manifests:
        if manifest["kind"] == "StatefulSet" and manifest["metadata"]["name"] != NODES:
            assert len(manifest["spec"]["template"]["spec"]["containers"]) == 1
    config_map = next(
        manifest
        for manifest in manifests
        if manifest["kind"] == "ConfigMap" and "config.yaml" in manifest["data"]
    )
    assert get_YAML().load(config_map["data"]["config.yaml"]) == {
        "targets": [],
        "endpoints": [],
        "requests": [],
        "actions": [],
    }
    if mix_enabled:
        scripts = next(
            manifest
            for manifest in manifests
            if manifest["metadata"]["name"] == MIX_SCRIPTS_CONFIG_MAP
        )
        assert set(scripts["data"]) == {"prepare_mix.sh", "start_storage.sh"}
        assert "/api/storage/v1/debug/info" in scripts["data"]["prepare_mix.sh"]
        assert "--dht-mix-proxy=" in scripts["data"]["start_storage.sh"]
    assert apply.call_count == manifest_count
    assert all(call.kwargs["dry_run"] for call in apply.call_args_list)
    cleanup.assert_not_called()
    transfer.assert_not_called()
    assert exp.metadata["stack"]["nodes_per_statefulset"] == ([1, 4, 4] if mix_enabled else [1, 4])
    assert (tmp_path / "metadata.json").exists()


@pytest.mark.asyncio
@pytest.mark.parametrize("passed", [True, False])
@pytest.mark.parametrize("mix_enabled", [True, False])
async def test_transfer_result_and_logs_survive_cleanup_and_failure(
    monkeypatch, tmp_path, passed, mix_enabled
):
    steps = []
    report = {
        "status": "passed" if passed else "failed",
        "stage": "complete" if passed else "confirm",
        "cid": "zTestCid",
    }
    if not passed:
        report["error"] = "Download receipt does not match the requested CID"
    transfer = AsyncMock(return_value=report)
    monkeypatch.setattr(logos_storage, "run_file_transfer", transfer)
    monkeypatch.setattr(base_experiment, "kubectl_apply", Mock())
    monkeypatch.setattr(base_experiment, "wait_for_rollout", AsyncMock())
    monkeypatch.setattr(
        base_experiment, "get_cleanup", Mock(return_value=lambda: steps.append("cleanup"))
    )
    monkeypatch.setattr(LogosStorageExperiment, "_wait_until_clear", Mock())

    def capture(*_args, **_kwargs):
        steps.append("logs")
        assert json.loads((tmp_path / "file_transfer.json").read_text()) == report
        return 3

    monkeypatch.setattr(logos_storage, "capture_pod_logs", capture)
    exp = LogosStorageExperiment(
        api_client=ApiClient(),
        config=config(verify_transfer=True, duration=0, num_nodes=4, mix_enabled=mix_enabled),
        namespace="storage-test",
        output_folder=tmp_path,
    )

    if passed:
        await exp.run()
    else:
        with pytest.raises(ExperimentFailed, match="requested CID"):
            await exp.run()

    transfer.assert_awaited_once_with(
        namespace="storage-test",
        source_pod="storage-nodes-0",
        target_pods=["storage-nodes-1", "storage-nodes-2", "storage-nodes-3"],
        file_size_bytes=1048576,
        timeout=600,
        api_port=8080,
        concurrency=3,
        transport="mix" if mix_enabled else "direct",
    )
    assert steps == ["logs"] + ["cleanup"] * (12 if mix_enabled else 9)
    assert (tmp_path / "metadata.json").exists()
